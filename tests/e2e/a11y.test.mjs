import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, openGame, solveCurrent, url } from './helpers.mjs'

test('keyboard play: arrows reclaim focus from HUD buttons, Space turns the focused tile', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser)
  await page.evaluate(() => window.__hemisphere.startLevel(1, 2))
  await page.waitForTimeout(300)
  await page.click('#btn-hint')
  const afterHint = await page.evaluate(() => window.__hemisphere.moves)
  await page.keyboard.press('ArrowLeft')
  assert.equal(await page.evaluate(() => document.activeElement.id), 'stage')
  await page.keyboard.press('Space')
  await page.waitForTimeout(50)
  const m = await page.evaluate(() => window.__hemisphere.moves)
  assert.ok(m === afterHint + 1 || m === afterHint, 'Space turned a tile, not the hint button again')
  assert.equal(await page.evaluate(() => window.__hemisphere.hints), 1, 'Space did not press the Hint button again')
  assert.ok((await page.textContent('#live')).length > 0, 'cell was announced')
  assert.deepEqual(errors, [])
  await browser.close()
})

test('panels trap focus and Escape closes only the top one', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser)
  await page.evaluate(() => window.__hemisphere.startLevel(1, 0))
  await page.keyboard.press('Escape')
  await page.waitForSelector('.panel')
  for (let k = 0; k < 12; k++) {
    await page.keyboard.press('Tab')
    const inPanel = await page.evaluate(() => !!document.activeElement.closest('.panel') || document.activeElement === document.body)
    assert.ok(inPanel, 'focus stayed in the dialog')
  }
  await page.click('.panel [data-act="settings"]')
  await page.waitForTimeout(300)
  assert.equal(await page.locator('.panel').count(), 2)
  const names = await page.evaluate(() => [...document.querySelectorAll('.panel')].map(p => document.getElementById(p.getAttribute('aria-labelledby')).textContent))
  assert.deepEqual(names, ['Menu', 'Settings'])
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.panel').count(), 1)
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('.panel').count(), 0)
  assert.equal(await page.evaluate(() => window.__hemisphere.mode), 'game')
  assert.deepEqual(errors, [])
  await browser.close()
})

test('language switch keeps focus and translates the completion card', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser)
  await page.evaluate(() => window.__hemisphere.startLevel(0, 0))
  await solveCurrent(page)
  await page.waitForTimeout(400)
  const before = await page.textContent('#btn-next')
  await page.click('#hud [data-act="menu"]')
  await page.click('.panel [data-act="settings"]')
  await page.focus('#lang-id')
  await page.keyboard.press('Enter')
  await page.waitForTimeout(150)
  assert.equal(await page.evaluate(() => document.activeElement.id), 'lang-id')
  await page.keyboard.press('Escape'); await page.keyboard.press('Escape')
  const after = await page.textContent('#btn-next')
  assert.equal(before, 'Next')
  assert.equal(after, 'Lanjut')
  assert.match(await page.textContent('#complete-sub'), /langkah/)
  assert.deepEqual(errors, [])
  await browser.close()
})

test('a corrupted save still boots to a playable title', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  for (const raw of ['null', '{"settings":null}', '{"progress":{"stars":null}}', '{oops']) {
    const ctx = await browser.newContext()
    await ctx.route(/^https?:\/\//, r => r.abort())
    await ctx.addInitScript(v => { try { localStorage.setItem('hemisphere.v1', v) } catch {} }, raw)
    const page = await ctx.newPage()
    const errors = []
    page.on('pageerror', e => errors.push(String(e)))
    await page.goto(url)
    await page.waitForFunction(() => window.__hemisphere !== undefined, null, { timeout: 8000 })
    await page.click('#btn-play')
    await page.waitForFunction(() => window.__hemisphere.mode === 'game')
    assert.deepEqual(errors, [], raw)
    await ctx.close()
  }
  await browser.close()
})
