import test from 'node:test'
import assert from 'node:assert/strict'
import { chromium, openGame, solveCurrent } from './helpers.mjs'

const SHOTS = process.env.SHOTS || ''

test('title -> play -> tap to turn -> solve -> next level (desktop)', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser, { width: 1440, height: 900 })
  await page.waitForSelector('#screen-title:not([hidden])')
  await page.waitForFunction(() => document.querySelector('#loading-note').style.visibility === 'hidden', null, { timeout: 15000 })
  await page.click('#btn-play')
  await page.waitForFunction(() => window.__hemisphere.mode === 'game')
  assert.equal(await page.evaluate(() => window.__hemisphere.level.key), 'lines-1')
  assert.match(await page.textContent('#coach'), /^Click /)
  // tap the middle tile of level 1 (3x1): one tap solves it
  const [x, y] = await page.evaluate(() => window.__hemisphere.cellCenter(1, 0))
  await page.waitForTimeout(400)
  if (SHOTS) await page.screenshot({ path: SHOTS + '/l1-start.png' })
  await page.mouse.click(x, y)
  await page.waitForSelector('#screen-complete:not([hidden])', { timeout: 8000 })
  assert.equal(await page.evaluate(() => window.__hemisphere.moves), 1)
  assert.match(await page.textContent('#complete-sub'), /Solved in 1 move ·/)
  assert.equal(await page.evaluate(() => document.querySelector('#btn-undo').disabled), true)
  if (SHOTS) await page.screenshot({ path: SHOTS + '/l1-done.png' })
  await page.click('#btn-next')
  await page.waitForFunction(() => window.__hemisphere.level.key === 'lines-2')
  const prog = await page.evaluate(() => window.__hemisphere.progress())
  assert.equal(prog.stars['lines-1'], 3)
  assert.deepEqual(errors, [])
  await browser.close()
})

test('right-click turns counter-clockwise, undo restores', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser)
  await page.evaluate(() => window.__hemisphere.startLevel(1, 3))
  await page.waitForTimeout(300)
  const before = await page.evaluate(() => window.__hemisphere.moves)
  assert.equal(before, 0)
  const lv = await page.evaluate(() => window.__hemisphere.level)
  const [x, y] = await page.evaluate(() => window.__hemisphere.cellCenter(1, 1))
  await page.mouse.click(x, y, { button: 'right' })
  await page.waitForTimeout(100)
  assert.equal(await page.evaluate(() => window.__hemisphere.moves), 1)
  await page.click('#btn-undo')
  assert.equal(await page.evaluate(() => window.__hemisphere.moves), 0)
  assert.ok(lv.w >= 4)
  assert.deepEqual(errors, [])
  await browser.close()
})

test('phone: tap and long-press, solve a brain-shaped level, no overflow', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser, { width: 390, height: 844, mobile: true, locale: 'id-ID' })
  await page.waitForFunction(() => document.querySelector('#loading-note').style.visibility === 'hidden', null, { timeout: 20000 })
  if (SHOTS) await page.screenshot({ path: SHOTS + '/phone-title.png' })
  await page.evaluate(() => window.__hemisphere.startLevel(4, 2))
  await page.waitForTimeout(800)
  if (SHOTS) await page.screenshot({ path: SHOTS + '/phone-brain-start.png' })
  const [x, y] = await page.evaluate(() => window.__hemisphere.cellCenter(2, 3))
  await page.touchscreen.tap(x, y)
  await page.waitForTimeout(200)
  const m1 = await page.evaluate(() => window.__hemisphere.moves)
  assert.ok(m1 <= 1)
  await solveCurrent(page)
  await page.waitForTimeout(1200)
  if (SHOTS) await page.screenshot({ path: SHOTS + '/phone-brain-done.png' })
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth - innerWidth)
  assert.equal(overflow, 0)
  // Indonesian UI was auto-detected
  assert.equal(await page.evaluate(() => document.documentElement.lang), 'id')
  assert.deepEqual(errors, [])
  await browser.close()
})

test('restarting right after a solve never shows a stale completion card', async t => {
  const browser = await chromium.launch()
  t.after(() => browser.close().catch(() => {}))
  const { page, errors } = await openGame(browser)
  await page.evaluate(() => window.__hemisphere.startLevel(0, 0))
  await page.waitForTimeout(300)
  const [x, y] = await page.evaluate(() => window.__hemisphere.cellCenter(1, 0))
  await page.mouse.click(x, y)
  await page.waitForFunction(() => window.__hemisphere.solved, null, { timeout: 5000 })
  await page.keyboard.press('r')
  await page.waitForTimeout(2200)
  assert.equal(await page.evaluate(() => window.__hemisphere.mode), 'game')
  assert.equal(await page.evaluate(() => document.querySelector('#screen-complete').hidden), true)
  assert.equal(await page.evaluate(() => window.__hemisphere.moves), 0)
  assert.deepEqual(errors, [])
  await browser.close()
})
